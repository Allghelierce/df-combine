"""PX4 (.px4) and ArduPilot (.apj) firmware containers.

Both projects ship firmware for flight controllers as a JSON document whose
``image`` field contains the zlib-compressed, base64-encoded flash image
(generated by PX4's ``px_mkfw.py`` / ArduPilot's ``make_apj.py``).  Known
``magic`` values are ``PX4FWv1`` (PX4) and ``APJFWv1`` (ArduPilot).
"""
from __future__ import annotations

import base64
import binascii
import json
import zlib
from dataclasses import dataclass, field
from typing import Any

MAGICS = {"PX4FWv1": "PX4", "APJFWv1": "ArduPilot"}
METADATA_KEYS = (
    "board_id", "board_revision", "magic", "description", "summary", "version",
    "git_identity", "git_hash", "build_time", "image_size", "image_maxsize", "flash_total",
    "flash_free", "extflash_total", "extflash_free", "USBID", "manufacturer",
    "brand_name", "signed_firmware", "airframe_xml", "parameter_xml",
)


class ContainerError(ValueError):
    pass


@dataclass
class FirmwareContainer:
    platform: str
    magic: str
    metadata: dict[str, Any]
    images: dict[str, bytes] = field(default_factory=dict)  # name -> decoded image


def looks_like_container(head: bytes) -> bool:
    text = head.lstrip()
    if not text.startswith(b"{"):
        return False
    return any(m.encode() in head for m in MAGICS) or (b'"image"' in head and b'"board_id"' in head)


def _inflate(blob_b64: str, limit: int) -> bytes:
    try:
        compressed = base64.b64decode(blob_b64, validate=False)
    except (binascii.Error, ValueError) as exc:
        raise ContainerError(f"image is not valid base64: {exc}") from None
    d = zlib.decompressobj()
    try:
        out = d.decompress(compressed, limit + 1)
    except zlib.error as exc:
        raise ContainerError(f"image is not valid zlib data: {exc}") from None
    if len(out) > limit or d.unconsumed_tail:
        raise ContainerError(f"decoded image exceeds limit of {limit} bytes")
    return out


def parse_container(raw: bytes, max_image_bytes: int) -> FirmwareContainer:
    try:
        doc = json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ContainerError(f"not a JSON firmware container: {exc}") from None
    if not isinstance(doc, dict) or "image" not in doc:
        raise ContainerError("JSON document has no 'image' field")
    magic = str(doc.get("magic", ""))
    platform = MAGICS.get(magic, "unknown")
    meta = {k: doc[k] for k in METADATA_KEYS if k in doc and not isinstance(doc[k], (dict, list))}
    # Avoid copying multi-MB XML blobs into metadata; just record presence.
    for k in ("airframe_xml", "parameter_xml"):
        if k in meta:
            meta[k] = f"<present, {len(str(doc[k]))} chars>"
    images: dict[str, bytes] = {}
    images["image.bin"] = _inflate(str(doc["image"]), max_image_bytes)
    if doc.get("extf_image"):
        images["extf_image.bin"] = _inflate(str(doc["extf_image"]), max_image_bytes)
    declared = doc.get("image_size")
    if isinstance(declared, int) and declared != len(images["image.bin"]):
        meta["image_size_mismatch"] = f"declared {declared}, decoded {len(images['image.bin'])}"
    return FirmwareContainer(platform=platform, magic=magic, metadata=meta, images=images)
