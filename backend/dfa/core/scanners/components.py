@dataclass
class Component:
    name: str
    version: str
    sources: list[str] = field(default_factory=list)
    method: str = "string-match"

    def to_dict(self) -> dict:
        return asdict(self)


def parse_version(v: str) -> tuple:
    parts: list = []
    for tok in re.findall(r"\d+|[a-z]+", v.lower()):
        if tok.isdigit():
            parts.append((1, int(tok)))
        elif tok in ("rc", "beta", "alpha", "pre", "dev"):
            parts.append((0, tok))  # pre-releases sort before releases
        elif len(tok) <= 2:
            parts.append((1, sum((ord(c) - 96) * 27 ** i for i, c in enumerate(reversed(tok)))))
        else:
            parts.append((1, 0))
    parts.append((0, "~"))  # end marker: sorts after pre-release tags, before any further number
    return tuple(parts)


def version_in_range(v: str, entry: dict) -> bool:
    pv = parse_version(v)
    if "min" in entry and pv < parse_version(entry["min"]):
        return False
    if "max_exclusive" in entry and not pv < parse_version(entry["max_exclusive"]):
        return False
    if "max_inclusive" in entry and pv > parse_version(entry["max_inclusive"]):
        return False
    return True


def load_kb() -> dict:
    kb = json.loads(KB_PATH.read_text())
    extra = os.environ.get("DFA_COMPONENT_KB")
    if extra and Path(extra).is_file():
        kb["entries"] = kb["entries"] + json.loads(Path(extra).read_text()).get("entries", [])
    return kb


def match_line(line: str) -> list[tuple[str, str]]:
    """(component, version) for every fingerprint that matches one string/line."""
    line = line[:600]
    return [(name, m.group(1)) for name, pat in FINGERPRINTS if (m := pat.search(line))]


def package_component(package: str) -> str | None:
    """Component name for an installed binary package, or None if it is not tracked."""
    package = package.split(":", 1)[0]  # tolerate "name:arch"
    if package in PACKAGE_COMPONENTS:
        return PACKAGE_COMPONENTS[package]
    for pat, comp in PACKAGE_COMPONENT_PATTERNS:
        if pat.fullmatch(package):
            return comp
    return None


def upstream_version(version: str) -> str | None:
    """Upstream part of a dpkg/opkg version: '1:9.2p1-2+deb12u3' -> '9.2p1'.

    Returns None for versions that do not look like an upstream release (e.g. OpenWrt
    git snapshots '2023-09-08-e5ccbfc6'), which would never compare sensibly.
    """
    v = re.sub(r"^\d+:", "", version.strip())  # epoch
    if "-" in v:
        v = v.rsplit("-", 1)[0]  # Debian/opkg revision
    v = re.split(r"[+~]", v, maxsplit=1)[0]  # +dfsg, +really, ~rc, ~deb12u1 ...
    v = re.sub(r"(?:\.(?:dfsg|ds|repack)\d*|-stable)$", "", v)  # zlib '1.2.13.dfsg', wolfSSL '5.6.4-stable'
    return v if re.fullmatch(r"\d[\w.]*", v) else None


def parse_package_status(text: str) -> list[tuple[str, str]]:
    """(component, upstream version) for each installed, mapped package in a dpkg/opkg status file."""
    out: list[tuple[str, str]] = []
    fields: dict[str, str] = {}

    def flush() -> None:
        status = fields.get("status", "").split()
        # want=install (or hold: installed and pinned), state=installed. Excludes e.g. "deinstall ok config-files".
        if len(status) >= 2 and status[0] in ("install", "hold") and status[-1] == "installed":
            comp = package_component(fields.get("package", ""))
            version = upstream_version(fields.get("version", ""))
            if comp and version:
                out.append((comp, version))
        fields.clear()

    for line in text.splitlines():
        if not line.strip():
            flush()
        elif line[0] not in " \t":  # continuation lines (Description, Conffiles) carry nothing we need
            key, sep, val = line.partition(":")
            if sep:
                fields[key.strip().lower()] = val.strip()
    flush()
    return out


def is_package_db(art: Artifact) -> bool:
    name = "/" + art.name.replace("\\", "/").lstrip("/")
    return name.endswith(PACKAGE_DB_SUFFIXES)


def _read_package_db(ctx: ScanContext, art: Artifact) -> str:
    try:
        with ctx.paths[art.id].open("rb") as fp:
            return fp.read(ctx.limits.max_scan_bytes_per_file).decode("utf-8", "replace")
    except (OSError, KeyError):
        return ""


def fingerprint(ctx: ScanContext) -> list[Component]:
    found: dict[tuple[str, str], Component] = {}

    def add(name: str, version: str, src: str, method: str) -> None:
        comp = found.setdefault((name, version), Component(name=name, version=version, method=method))
        if len(comp.sources) < 5 and src not in comp.sources:
            comp.sources.append(src)

    for art in ctx.content_artifacts():
        if is_package_db(art):
            # Parsed structurally; free-text descriptions in it are not scanned for version strings.
            for name, version in parse_package_status(_read_package_db(ctx, art)):
                add(name, version, ctx.where(art), "package-db")
            continue
        if art.format in ("text",):
            text = ctx.text(art) or ""
            lines = text.splitlines()[:20_000]
        elif art.format in ("elf", "raw", "cortexm_raw") or art.name.endswith((".so", ".ko")):
            lines = [s for _, s in ctx.strings(art)]
        else:
            continue
        for line in lines:
            for name, version in match_line(line):
                add(name, version, ctx.where(art), "string-match")
    # Drop zlib/openssl duplicates that are clearly test strings (e.g. version "0.0.0").
    return sorted((c for c in found.values() if not c.version.startswith("0.0")), key=lambda c: (c.name, c.version))


def assess(components: list[Component], kb: dict | None = None) -> list[Finding]:
    kb = kb or load_kb()
    out = []
    by_entry: dict[int, list[Component]] = defaultdict(list)
    entries = kb["entries"]
    for comp in components:
        for i, e in enumerate(entries):
            if e["component"] == comp.name and version_in_range(comp.version, e):
                by_entry[i].append(comp)
    for i, comps in by_entry.items():
        e = entries[i]
        for comp in comps:
            out.append(Finding(
                title=f"{e['title']} - {comp.name} {comp.version}",
                description=(e["description"] + f" Detected version string '{comp.version}' "
                             f"(knowledge base as of {kb.get('as_of', 'unknown')}). Version-based match only: "
                             "the fix may have been backported, so this is not a confirmed vulnerability."),
                severity=S(e["severity"]), classification=C.unverified, confidence=K.medium, source_tool=TOOL,
                rule_id=f"outdated-{comp.name}", affected_component=f"{comp.name} {comp.version}",
                remediation=f"Upgrade {comp.name} to a maintained release or confirm vendor backports.",
                evidence=[Evidence("string", f"{comp.name} version {comp.version}", src) for src in comp.sources[:5]],
                cwe="CWE-1104", references=list(e.get("references", [])) + list(e.get("cves", [])),
                tags=["outdated-component"] + list(e.get("cves", []))))
    return out
